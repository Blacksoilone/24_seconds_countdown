// 时序仿真测试平台
// 功能：驱动顶层模块的所有输入，监控输出，验证功能
`timescale 1ps/1ps  // 1ps 精度，匹配 SDF 文件

module top_timing_tb;
    
    // =================================================================
    // 1. 声明被测设计（DUT）的输入信号（必须是 reg 类型，因为要驱动）
    // =================================================================
    
    // 板载时钟输入（100MHz）
    reg sys_clk;
    
    // 板载复位输入（高电平有效）
    reg sys_reset;
    
    // 按键输入（4 个按键，低电平有效）
    reg [3:0] btn;
    
    // =================================================================
    // 2. 声明被测设计的输出信号（必须是 wire 类型，因为是观察）
    // =================================================================
    
    // 七段数码管段码输出（CA-DP）
    wire [7:0] seg_data;
    
    // 数码管位选输出（AN3-AN0）
    wire [3:0] an;
    
    // LED 输出（5 个 LED）
    wire [4:0] led;
    
    // =================================================================
    // 3. 实例化被测设计（DUT - Device Under Test）
    // =================================================================
    // 这里实例化你的顶层模块 top
    top uut (
        // 时钟和复位连接
        .sys_clk(sys_clk),      // 板载时钟输入
        .sys_reset(sys_reset),  // 板载复位输入
        
        // 按键连接
        .btn(btn),              // 按键输入
        
        // 外设输出连接
        .seg_data(seg_data),    // 数码管段码
        .an(an),                // 数码管位选  
        .led(led)               // LED 输出
    );
    
    // =================================================================
    // 4. 时钟生成（最关键的部分）
    // =================================================================
    // 为什么需要这个？
    // - FPGA 本身没有时钟源
    // - Clocking Wizard 需要外部时钟输入
    // - 必须模拟板载晶振的行为
    initial begin
        // 初始化时钟为 0
        sys_clk = 1'b0;
        
        // 无限循环生成 100MHz 时钟
        // 100MHz = 10ns 周期 = 10000ps
        // 50% 占空比 → 高电平 5ns，低电平 5ns
        // 5ns = 5000ps
        forever #5000 sys_clk = ~sys_clk;
    end
    
    // =================================================================
    // 5. 复位和按键控制
    // =================================================================
    // 为什么需要这个？
    // - FPGA 上电后需要复位
    // - 按键需要模拟真实操作
    initial begin
        // ========== 初始化 ==========
        // 复位信号置 1（激活复位）
        sys_reset = 1'b1;
        
        // 按键全部释放（高电平，因为按键低有效）
        btn = 4'b1111;
        
        // ========== 复位阶段 ==========
        // 保持复位 20ns（2 个时钟周期）
        // 确保所有寄存器正确初始化
        #20000;
        sys_reset = 1'b0;  // 释放复位
        
        // ========== 正常运行阶段 ==========
        // 等待 50ms，观察倒计时
        #50000000;
        
        // ========== 按键测试 ==========
        // 模拟按下左键（清零功能）
        // BTNL 对应 btn[2]，低电平有效
        btn = 4'b1011;  // btn[2] = 0，其他 = 1
        #100000;        // 按下 100ns（足够 CPU 采样）
        btn = 4'b1111;  // 释放按键

    end
    

endmodule